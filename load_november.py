def get_sheet():
    creds_dict = json.loads(GOOGLE_CREDENTIALS_JSON)
    scope = ["https://spreadsheets.google.com/feeds","https://www.googleapis.com/auth/drive"]
    creds = Credentials.from_service_account_info(creds_dict, scopes=scope)
    client = gspread.authorize(creds)
    return client.open_by_key(SPREADSHEET_ID).sheet1


def main():
    sheet = get_sheet()
    rows = sheet.get_all_values()

    print(f"現在の行数: {len(rows)}")

    # ヘッダー確認
    if not rows or rows[0] != HEADERS:
        print(f"ヘッダー不一致。現在: {rows[0] if rows else '空'}")
        print("中止します。先にsetup_sheet.pyを実行してください。")
        return

    # 既存の投稿日時を収集（重複防止）
    existing = set()
    for row in rows[1:]:
        if row and row[0].strip():
            existing.add(row[0].strip())

    print(f"既存データ数: {len(existing)}")

    # 11月の投稿を行データに変換
    new_rows = []
    for (month, day, hour, minute, body) in POSTS:
        dt = datetime(2026, month, day, hour, minute, tzinfo=JST)
        sched_str = dt.strftime("%Y-%m-%d %H:%M")
        weekday = WEEKDAY_MAP[dt.weekday()]

        if sched_str in existing:
            print(f"スキップ（既存）: {sched_str}")
            continue

        row = [
            sched_str,   # 投稿日時
            weekday,     # 曜日
            body,        # 投稿文
            "投稿前",    # 状態
            "",          # 投稿URL
            "", "", "", "", "",  # 再生数〜いいね数
            "", "", "", "", "",  # いいね率〜再投稿率
            "",          # 投稿ID
        ]
        new_rows.append(row)

    if not new_rows:
        print("追加するデータがありません。")
        return

    print(f"追加予定: {len(new_rows)}行")

    # バッチで追加（Google Sheets API rate limit対策で分割）
    batch_size = 50
    for i in range(0, len(new_rows), batch_size):
        batch = new_rows[i:i+batch_size]
        sheet.append_rows(batch, value_input_option="USER_ENTERED")
        print(f"{i+len(batch)}行追加完了")

    print(f"\n完了！合計{len(new_rows)}行を追加しました。")


if __name__ == "__main__":
    main()
