    # headerの列数に合わせて空の行を作成し、必要な列に値をセット
    num_cols = len(header)

    batch_data = []
    for row_data in new_rows:
        new_row = [""] * num_cols
        new_row[col_sched]  = row_data[0]  # 投稿日時
        if col_weekday is not None:
            new_row[col_weekday] = row_data[1]  # 曜日
        new_row[col_status] = row_data[2]  # 状態
        new_row[col_body]   = row_data[3]  # 投稿文
        batch_data.append(new_row)

    # バッチで追加
    sheet.append_rows(batch_data, value_input_option="USER_ENTERED")
    print(f"完了! 行{start_row}から{start_row + len(new_rows) - 1}に追加しました")
    print(f"期間: {new_rows[0][0]} 〜 {new_rows[-1][0]}")

